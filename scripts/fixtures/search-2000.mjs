// Generates tests/fixtures/large/search-2000.postgres.sql (kept out of fixtures/sql/, whose
// files every parser robustness test mutates): 2,000 tables × 20 columns (40,000
// columns) for timing search in the browser (P2-T07). Deterministic; no foreign keys, so the
// auto-layout stays quick. Usage: node scripts/fixtures/search-2000.mjs
import { writeFileSync } from "node:fs";

const NOUNS = [
  "user",
  "order",
  "item",
  "product",
  "invoice",
  "account",
  "event",
  "audit",
  "shipment",
  "payment",
];
const FIELDS = [
  "name",
  "status",
  "amount",
  "code",
  "note",
  "score",
  "label",
  "region",
  "level",
  "kind",
];
const TYPES = ["text", "integer", "numeric(10, 2)", "boolean", "varchar(64)", "jsonb"];

let sql =
  "-- 2,000 tables × 20 columns for search timing (generated by scripts/fixtures/search-2000.mjs).\n";
for (let t = 0; t < 2000; t++) {
  const noun = NOUNS[t % NOUNS.length];
  const other = NOUNS[(t * 7 + 3) % NOUNS.length];
  const cols = [
    "  id bigint PRIMARY KEY",
    "  created_at timestamptz NOT NULL",
    `  ${other}_id bigint`,
  ];
  for (let c = 3; c < 20; c++) {
    const field = FIELDS[(t + c) % FIELDS.length];
    cols.push(`  ${noun}_${field}_${c} ${TYPES[(t + c) % TYPES.length]}`);
  }
  sql += `CREATE TABLE ${noun}_${other}_${String(t).padStart(4, "0")} (\n${cols.join(",\n")}\n);\n`;
}
writeFileSync(new URL("../../tests/fixtures/large/search-2000.postgres.sql", import.meta.url), sql);
console.log(`${(sql.length / 1e6).toFixed(2)} MB`);
