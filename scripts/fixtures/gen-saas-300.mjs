// Generates tests/fixtures/synthetic/saas-300.postgres.sql: a 300-table PostgreSQL schema of the
// size SchemaFlow is built for (BB-P3). 3 schemas (core, billing, analytics) of 100 tables each;
// 4 wide tables (60–150 columns); about 15% isolated tables; composite primary keys; a
// self-reference; inline REFERENCES plus `ALTER TABLE ONLY … ADD CONSTRAINT … FOREIGN KEY`; a few
// CHECKs with `char_length` and `::text` casts.
//
// Deterministic (fixed seed). `node scripts/fixtures/gen-saas-300.mjs` writes the file; `--stdout`
// prints it instead (used by the test that checks the committed file is up to date).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SEED = 20261120;
/** mulberry32: small, fast, deterministic. */
function prng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const SCHEMAS = ["core", "billing", "analytics"];
const PER_SCHEMA = 100;
const WIDE = new Map([
  ["core.t001_wide", 150],
  ["core.t002_wide", 90],
  ["billing.t001_wide", 120],
  ["analytics.t001_wide", 60],
]);
const COLUMN_TYPES = [
  "text",
  "integer",
  "boolean",
  "numeric(12,2)",
  "timestamp with time zone",
  "character varying(255)",
  "bigint",
  "jsonb",
];

export function generate() {
  const rand = prng(SEED);
  const pick = (list) => list[Math.floor(rand() * list.length)];

  // Table plan: [schema, name, kind]. kind: "wide" | "isolated" | "link" | "normal".
  const tables = [];
  for (const schema of SCHEMAS) {
    for (let i = 1; i <= PER_SCHEMA; i++) {
      const n = String(i).padStart(3, "0");
      const wideName = `t${n}_wide`;
      if (WIDE.has(`${schema}.${wideName}`)) {
        tables.push({ schema, name: wideName, kind: "wide", cols: WIDE.get(`${schema}.${wideName}`) });
        continue;
      }
      const roll = rand();
      const kind = roll < 0.15 ? "isolated" : roll < 0.3 ? "link" : "normal";
      tables.push({ schema, name: `t${n}_${kind === "link" ? "link" : "entity"}`, kind });
    }
  }
  const qn = (t) => `${t.schema}.${t.name}`;

  // Referenceable parents: normal and wide tables (single-column integer `id` primary key).
  const parents = tables.filter((t) => t.kind === "normal" || t.kind === "wide");
  const out = [];
  const alters = [];
  out.push("-- Synthetic SaaS schema (BB-P3). Generated by scripts/fixtures/gen-saas-300.mjs.");
  out.push("SET statement_timeout = 0;");
  out.push("SET client_encoding = 'UTF8';");
  for (const s of SCHEMAS) out.push(`CREATE SCHEMA ${s};`);
  out.push("");

  let checkCount = 0;
  let selfRefDone = false;
  tables.forEach((t, index) => {
    const lines = [];
    const before = parents.filter((p) => p !== t && tables.indexOf(p) < index);
    if (t.kind === "link") {
      // Composite primary key over two parent references (one inline, one ALTER).
      const a = before.length > 1 ? pick(before) : parents[0];
      let b = before.length > 1 ? pick(before) : parents[1];
      if (b === a) b = parents[2];
      lines.push(`  a_id integer NOT NULL REFERENCES ${qn(a)}(id)`);
      lines.push("  b_id integer NOT NULL");
      lines.push("  created_at timestamp with time zone DEFAULT now() NOT NULL");
      lines.push("  CONSTRAINT " + `${t.name}_pkey PRIMARY KEY (a_id, b_id)`);
      alters.push(
        `ALTER TABLE ONLY ${qn(t)}\n    ADD CONSTRAINT ${t.name}_b_id_fkey FOREIGN KEY (b_id) REFERENCES ${qn(b)}(id);`,
      );
    } else {
      lines.push("  id integer NOT NULL");
      if (t.kind === "wide") {
        for (let c = 1; c < t.cols; c++) {
          lines.push(`  c${String(c).padStart(3, "0")} ${COLUMN_TYPES[c % COLUMN_TYPES.length]}`);
        }
      } else {
        lines.push("  name character varying(120) NOT NULL");
        lines.push("  status text DEFAULT 'active'::text NOT NULL");
        lines.push("  created_at timestamp with time zone DEFAULT now() NOT NULL");
        if (t.kind === "normal" && before.length > 0) {
          const refs = 1 + Math.floor(rand() * 3);
          const used = new Set();
          for (let r = 0; r < refs; r++) {
            const p = pick(before);
            if (used.has(p)) continue;
            used.add(p);
            const col = `${p.name.replace(/^t\d+_/, "p" + String(tables.indexOf(p)).padStart(3, "0") + "_")}_id`;
            if (r === 0) lines.push(`  ${col} integer REFERENCES ${qn(p)}(id)`);
            else {
              lines.push(`  ${col} integer`);
              alters.push(
                `ALTER TABLE ONLY ${qn(t)}\n    ADD CONSTRAINT ${t.name}_${col}_fkey FOREIGN KEY (${col}) REFERENCES ${qn(p)}(id);`,
              );
            }
          }
        }
        if (t.kind === "normal" && !selfRefDone && t.schema === "core" && index > 5) {
          selfRefDone = true;
          lines.push("  parent_id integer");
          alters.push(
            `ALTER TABLE ONLY ${qn(t)}\n    ADD CONSTRAINT ${t.name}_parent_fkey FOREIGN KEY (parent_id) REFERENCES ${qn(t)}(id);`,
          );
        }
        if (t.kind === "normal" && checkCount < 6 && index % 7 === 0) {
          checkCount++;
          lines.push(
            checkCount % 2
              ? `  CONSTRAINT ${t.name}_name_check CHECK ((char_length(name) > 0))`
              : `  CONSTRAINT ${t.name}_status_check CHECK ((status = ANY (ARRAY['active'::text, 'archived'::text])))`,
          );
        }
      }
      lines.push(`  CONSTRAINT ${t.name}_pkey PRIMARY KEY (id)`);
    }
    out.push(`CREATE TABLE ${qn(t)} (\n${lines.join(",\n")}\n);`);
    out.push("");
  });
  out.push(...alters);
  out.push("");
  return out.join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const text = generate();
  if (process.argv.includes("--stdout")) process.stdout.write(text);
  else {
    const file = fileURLToPath(
      new URL("../../tests/fixtures/synthetic/saas-300.postgres.sql", import.meta.url),
    );
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote ${file}`);
  }
}
