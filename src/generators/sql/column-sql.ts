import type { Column, Table } from "@/domain/schema/types";
import { sqlString } from "../text/escape";
import type { SqlContext } from "./context";
import { renderDefault } from "./defaults";
import { isUnindexableOnMysql, mapType, mysqlKeyType } from "./type-map";

const SERIAL = /^(small|big)?serial[248]?$/i;

export interface RenderedColumn {
  /** `name type constraints…`, without the trailing comma. */
  line: string;
  /** CHECK expressions this column needs (enums on dialects without enum types). */
  checks: string[];
  /** SQLite `INTEGER PRIMARY KEY AUTOINCREMENT`: the table-level PRIMARY KEY is then omitted. */
  inlinePrimaryKey: boolean;
}

interface ColumnType {
  sql: string;
  check?: string;
}

function columnType(ctx: SqlContext, col: Column): ColumnType {
  const { to, schema, tally, faithful } = ctx;
  const dt = col.dataType;
  const enumDef = dt.enumName ? schema.enums[dt.enumName] : undefined;
  const name = ctx.ident(col.name);

  if (dt.isArray) {
    if (to === "postgresql") {
      if (faithful) return { sql: dt.raw };
      const element = enumDef
        ? ctx.ident(enumDef.name)
        : mapType({ ...dt, isArray: false }, ctx.from, to, ctx.isPrisma).sql;
      return { sql: `${element}[]` };
    }
    tally.add(`Array columns are stored as ${to === "mysql" ? "JSON" : "TEXT"}.`);
    return { sql: to === "mysql" ? "json" : "text" };
  }

  if (enumDef) {
    if (to === "postgresql") return { sql: ctx.ident(enumDef.name) };
    if (to === "mysql") {
      return { sql: `ENUM(${enumDef.values.map((v) => sqlString(v, "mysql")).join(", ")})` };
    }
    tally.add("Enum columns are approximated as TEXT with a CHECK constraint.");
    return {
      sql: "text",
      check: `${name} IN (${enumDef.values.map((v) => sqlString(v, to)).join(", ")})`,
    };
  }

  // MySQL's inline ENUM('a', 'b'): only MySQL has it, so other targets get TEXT + CHECK.
  if (dt.base.toLowerCase() === "enum" && dt.params?.length) {
    if (to === "mysql") return { sql: dt.raw };
    tally.add("Enum columns are approximated as TEXT with a CHECK constraint.");
    const values = dt.params.map((p) => (p.startsWith("'") ? p : sqlString(p, to)));
    return { sql: "text", check: `${name} IN (${values.join(", ")})` };
  }

  if (faithful) return { sql: dt.raw };
  if (to === "mysql" && ctx.keyColumns.has(col.id) && isUnindexableOnMysql(dt)) {
    tally.add("TEXT/BLOB columns used in keys are converted to VARCHAR(255)/VARBINARY(255).");
    return { sql: mysqlKeyType(dt) };
  }
  const mapped = mapType(dt, ctx.from, to, ctx.isPrisma);
  if (!mapped.exact) {
    tally.add(
      mapped.sql === dt.raw
        ? `Type "${dt.raw}" is not known to ${to}; copied as written.`
        : `Type "${dt.raw}" is approximated as "${mapped.sql}".`,
    );
  }
  return { sql: mapped.sql };
}

/** One column definition for the target dialect. */
export function renderColumn(ctx: SqlContext, table: Table, col: Column): RenderedColumn {
  const { to, tally } = ctx;
  const type = columnType(ctx, col);
  const parts = [ctx.ident(col.name), type.sql];
  let inlinePrimaryKey = false;

  const autoincrement = col.default?.kind === "autoincrement";
  if (autoincrement && to === "sqlite") {
    const pk = table.primaryKey?.columnIds;
    if (pk?.length === 1 && pk[0] === col.id) {
      parts[1] = "integer";
      parts.push("PRIMARY KEY AUTOINCREMENT");
      inlinePrimaryKey = true;
    } else {
      tally.add("AUTOINCREMENT is only available on a single-column primary key; dropped.");
    }
  }
  if (!inlinePrimaryKey && !col.nullable) parts.push("NOT NULL");

  if (col.default && !autoincrement) {
    const rendered = renderDefault(col.default, to, ctx.faithful, ctx.from);
    if (rendered?.unportable) ctx.leftOut.defaults.push(`${table.name}.${col.name}`);
    else if (rendered) {
      parts.push(`DEFAULT ${rendered.sql}`);
      if (rendered.copied && col.default.kind !== "literal") ctx.copied.add(table.id);
    } else tally.add("Defaults without a SQL equivalent (Prisma cuid()) were dropped.");
  }
  if (autoincrement && to === "postgresql" && !(ctx.faithful && SERIAL.test(col.dataType.base))) {
    parts.push("GENERATED BY DEFAULT AS IDENTITY");
  }
  if (autoincrement && to === "mysql") parts.push("AUTO_INCREMENT");
  if (to === "mysql" && col.comment) parts.push(`COMMENT ${sqlString(col.comment, "mysql")}`);

  return { line: parts.join(" "), checks: type.check ? [type.check] : [], inlinePrimaryKey };
}
